package ortus.boxlang.runtime;

import static com.google.common.truth.Truth.assertThat;
import static org.junit.jupiter.api.Assumptions.assumeTrue;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.attribute.PosixFilePermissions;
import java.util.Comparator;
import java.util.List;
import java.util.concurrent.TimeUnit;
import java.util.stream.Stream;

import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.condition.DisabledOnOs;
import org.junit.jupiter.api.condition.OS;
import org.junit.jupiter.api.io.TempDir;

/**
 * Regression test for the generated Unix launcher: BOXLANG_HOME and the install directory contain
 * spaces, and the launcher must still start the JVM and run a script.
 *
 * The launcher is generated by the startShadowScripts task and the runtime is loaded from the jar
 * in build/libs, so the test is skipped when either artifact is missing.
 */
@DisabledOnOs( OS.WINDOWS )
public class LauncherSpacedPathTest {

	@DisplayName( "It starts when BOXLANG_HOME and the install directory contain spaces" )
	@Test
	void testLauncher_pathsWithSpaces_startsAndRunsScript( @TempDir Path tempDir ) throws Exception {
		Path	launcher	= Path.of( "build/scriptsShadow/boxlang" ).toAbsolutePath();
		Path	runtimeJar	= findRuntimeJar();

		assumeTrue( Files.isRegularFile( launcher ), "Run startShadowScripts to generate " + launcher );
		assumeTrue( runtimeJar != null, "Run the jar task to produce a BoxLang runtime jar in build/libs" );

		Path	install	= Files.createDirectories( tempDir.resolve( "install dir" ) );
		Path	bin		= Files.createDirectories( install.resolve( "bin" ) );
		Path	lib		= Files.createDirectories( install.resolve( "lib" ) );
		Path	home	= Files.createDirectories( tempDir.resolve( "box home" ) );
		Path	work	= Files.createDirectories( tempDir.resolve( "work" ) );

		Path	staged	= Files.copy( launcher, bin.resolve( "boxlang" ) );
		Files.setPosixFilePermissions( staged, PosixFilePermissions.fromString( "rwxr-xr-x" ) );
		Files.copy( runtimeJar, lib.resolve( runtimeJar.getFileName() ) );
		Files.writeString( work.resolve( "check.bxs" ), "println( 'launcher-ok' )" );

		ProcessBuilder builder = new ProcessBuilder( List.of( staged.toString(), "check.bxs" ) ).directory( work.toFile() );
		builder.environment().put( "BOXLANG_HOME", home.toString() );
		builder.redirectErrorStream( true );
		Process	process	= builder.start();
		String	output	= new String( process.getInputStream().readAllBytes() );

		assertThat( process.waitFor( 180, TimeUnit.SECONDS ) ).isTrue();
		assertThat( output ).doesNotContain( "Could not find or load main class" );
		assertThat( output ).contains( "launcher-ok" );
		assertThat( process.exitValue() ).isEqualTo( 0 );
	}

	/**
	 * Finds a runnable BoxLang jar in build/libs, ignoring the sources, javadoc, and sibling
	 * artifacts that are not a runtime.
	 */
	private Path findRuntimeJar() throws IOException {
		Path libsDirectory = Path.of( "build/libs" ).toAbsolutePath();
		if ( !Files.isDirectory( libsDirectory ) ) {
			return null;
		}
		try ( Stream<Path> files = Files.list( libsDirectory ) ) {
			return files
			    .filter( path -> path.getFileName().toString().matches( "boxlang-\\d.*\\.jar" ) )
			    .max( Comparator.comparing( path -> path.toFile().lastModified() ) )
			    .orElse( null );
		}
	}

}
