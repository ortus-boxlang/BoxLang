package ortus.boxlang.runtime;

import static com.google.common.truth.Truth.assertThat;
import static org.junit.jupiter.api.Assumptions.assumeTrue;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Comparator;
import java.util.List;
import java.util.concurrent.TimeUnit;
import java.util.stream.Stream;

import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.condition.EnabledOnOs;
import org.junit.jupiter.api.condition.OS;
import org.junit.jupiter.api.io.TempDir;

/**
 * End to end test of the generated Windows launcher: an environment file must reach the JVM.
 *
 * The launcher is generated by the startShadowScripts task and the runtime is loaded from the jar
 * in build/libs, so the test is skipped when either artifact is missing (a clean checkout that
 * only ran the compile tasks). Run `gradlew startShadowScripts` before the tests to enable it.
 */
@EnabledOnOs( OS.WINDOWS )
public class EnvFileLauncherTest {

	private static final String	VAR_NAME	= "BOX_ENV_FILE_TEST_VAR";
	private static final String	VAR_VALUE	= "hello-from-env-file";

	@DisplayName( "It exports values from .env to the JVM" )
	@Test
	void testDefaultEnvFileReachesTheJvm( @TempDir Path tempDir ) throws Exception {
		String output = runLauncher( tempDir, null );

		assertThat( output ).contains( VAR_NAME + "=[" + VAR_VALUE + "]" );
	}

	@DisplayName( "It exports values from the --envfile file to the JVM" )
	@Test
	void testEnvFileFlagReachesTheJvm( @TempDir Path tempDir ) throws Exception {
		String output = runLauncher( tempDir, "custom.env" );

		assertThat( output ).contains( VAR_NAME + "=[" + VAR_VALUE + "]" );
	}

	/**
	 * Stages a copy of the generated launcher next to a runtime jar and runs it with an
	 * environment file, returning everything the launcher wrote to standard output.
	 *
	 * @param tempDir     Scratch directory for the staged image.
	 * @param envFileName Environment file to pass with --envfile, or null for the default .env.
	 */
	private String runLauncher( Path tempDir, String envFileName ) throws IOException, InterruptedException {
		Path	launcher	= Path.of( "build/scriptsShadow/boxlang.bat" ).toAbsolutePath();
		Path	runtimeJar	= findRuntimeJar();

		assumeTrue( Files.isRegularFile( launcher ), "Run startShadowScripts to generate " + launcher );
		assumeTrue( runtimeJar != null, "Run the jar task to produce a BoxLang runtime jar in build/libs" );

		Path	binDirectory	= Files.createDirectories( tempDir.resolve( "bin" ) );
		Path	libDirectory	= Files.createDirectories( tempDir.resolve( "lib" ) );
		Path	homeDirectory	= Files.createDirectories( tempDir.resolve( "home" ) );
		Path	workDirectory	= Files.createDirectories( tempDir.resolve( "work" ) );

		Files.copy( launcher, binDirectory.resolve( "boxlang.bat" ) );
		Files.copy( runtimeJar, libDirectory.resolve( runtimeJar.getFileName() ) );
		Files.writeString( workDirectory.resolve( ".env" ), VAR_NAME + "=" + VAR_VALUE + System.lineSeparator() );
		Files.writeString( workDirectory.resolve( "custom.env" ), VAR_NAME + "=" + VAR_VALUE + System.lineSeparator() );
		Files.writeString(
		    workDirectory.resolve( "check.bxs" ),
		    "println( '" + VAR_NAME + "=[' & getSystemSetting( '" + VAR_NAME + "', 'MISSING' ) & ']' )"
		);

		List<String> command = new java.util.ArrayList<>( List.of( "cmd.exe", "/c", binDirectory.resolve( "boxlang.bat" ).toString() ) );
		if ( envFileName != null ) {
			command.add( "--envfile=" + workDirectory.resolve( envFileName ) );
		}
		command.add( "check.bxs" );

		ProcessBuilder builder = new ProcessBuilder( command ).directory( workDirectory.toFile() );
		builder.environment().put( "BOXLANG_HOME", homeDirectory.toString() );
		builder.redirectErrorStream( true );
		Process	process	= builder.start();
		String	output	= new String( process.getInputStream().readAllBytes() );

		assertThat( process.waitFor( 120, TimeUnit.SECONDS ) ).isTrue();

		return output;
	}

	/**
	 * Finds a runnable BoxLang jar in build/libs, ignoring the sources, javadoc, and sibling
	 * artifacts that are not a runtime.
	 */
	private Path findRuntimeJar() throws IOException {
		Path libsDirectory = Path.of( "build/libs" ).toAbsolutePath();
		if ( !Files.isDirectory( libsDirectory ) ) {
			return null;
		}
		try ( Stream<Path> files = Files.list( libsDirectory ) ) {
			return files
			    .filter( path -> path.getFileName().toString().matches( "boxlang-\\d.*\\.jar" ) )
			    .max( Comparator.comparing( path -> path.toFile().lastModified() ) )
			    .orElse( null );
		}
	}

}
